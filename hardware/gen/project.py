"""Write the KiCad project file (net classes, design rules) and custom DRC rules.

🔴 The clearance values below implement SPEC §4.8.2 (6 mm mains <-> low voltage,
3 mm between mains nets). Human review mandatory.
"""
import json
import os

import design

HERE = os.path.dirname(os.path.abspath(__file__))
PRO = os.path.join(HERE, "..", "dmxnow.kicad_pro")
DRU = os.path.join(HERE, "..", "dmxnow.kicad_dru")

MAINS_TO_LV = 6.0      # SPEC 4.8.2, reinforced insulation target
MAINS_TO_MAINS = 3.0   # functional insulation target
RELAY_CONTACT_GAP = 2.0  # COM/NO pads of K1 are 5 mm apart by relay design


def netclass(name, clearance, track, via_d=0.9, via_drill=0.35):
    return {
        "name": name, "clearance": clearance, "track_width": track,
        "via_diameter": via_d, "via_drill": via_drill,
        "microvia_diameter": 0.3, "microvia_drill": 0.1,
        "diff_pair_gap": 0.25, "diff_pair_via_gap": 0.25, "diff_pair_width": 0.2,
        "line_style": 0, "wire_width": 6, "bus_width": 12,
        "pcb_color": "rgba(0, 0, 0, 0.000)", "schematic_color": "rgba(0, 0, 0, 0.000)",
    }


def write_project():
    classes = [netclass("Default", 0.2, 0.25)]
    patterns = []
    for name, nc in design.NETCLASSES.items():
        via = (1.2, 0.6) if name in ("MAINS_PWR", "LED_PWR") else (0.9, 0.35)
        classes.append(netclass(name, nc["clearance"], nc["track"], *via))
        for n in nc["nets"]:
            patterns.append({"netclass": name, "pattern": n})
    pro = {
        "board": {
            "design_settings": {
                "defaults": {
                    "board_outline_line_width": 0.1, "copper_line_width": 0.2,
                    "copper_text_size_h": 1.5, "copper_text_size_v": 1.5, "copper_text_thickness": 0.3,
                    "other_line_width": 0.1, "silk_line_width": 0.12,
                    "silk_text_size_h": 1.0, "silk_text_size_v": 1.0, "silk_text_thickness": 0.15,
                },
                "rules": {
                    "min_clearance": 0.2, "min_connection": 0.2, "min_copper_edge_clearance": 0.5,
                    "min_hole_clearance": 0.25, "min_hole_to_hole": 0.25, "min_microvia_diameter": 0.2,
                    "min_microvia_drill": 0.1, "min_resolved_spokes": 1, "min_silk_clearance": 0.0,
                    "min_text_height": 0.8, "min_text_thickness": 0.08, "min_through_hole_diameter": 0.3,
                    "min_track_width": 0.2, "min_via_annular_width": 0.25, "min_via_diameter": 0.8,
                    "solder_mask_to_copper_clearance": 0.0, "use_height_for_length_calcs": True,
                },
                "rule_severities": {
                    "silk_overlap": "ignore", "silk_over_copper": "warning", "silk_edge_clearance": "warning",
                    "text_height": "warning", "text_thickness": "warning", "lib_footprint_issues": "ignore",
                    "lib_footprint_mismatch": "ignore", "footprint_type_mismatch": "ignore",
                    "courtyards_overlap": "error", "missing_courtyard": "ignore",
                },
                "track_widths": [0.0, 0.25, 0.4, 0.6, 1.0, 2.0, 5.0],
                "via_dimensions": [{"diameter": 0.0, "drill": 0.0}, {"diameter": 0.9, "drill": 0.35},
                                   {"diameter": 1.2, "drill": 0.6}],
            },
        },
        "meta": {"filename": "dmxnow.kicad_pro", "version": 1},
        "net_settings": {"classes": classes, "meta": {"version": 3},
                         "net_colors": None, "netclass_assignments": None, "netclass_patterns": patterns},
        "pcbnew": {"last_paths": {}, "page_layout_descr_file": ""},
        "schematic": {"drawing": {}, "legacy_lib_dir": "", "legacy_lib_list": []},
        "sheets": [], "text_variables": {},
    }
    with open(PRO, "w") as f:
        json.dump(pro, f, indent=2)


def write_rules():
    mains = " || ".join("A.NetClass == '%s'" % c for c in ("MAINS", "MAINS_PWR"))
    mains_b = " || ".join("B.NetClass == '%s'" % c for c in ("MAINS", "MAINS_PWR"))
    txt = """(version 1)
# dmxnow custom DRC rules - generated by hardware/gen/project.py
# 🔴 RELECTURE HUMAINE OBLIGATOIRE (SPEC 4.8.2)

(rule "mains_to_low_voltage"
  (condition "({a}) && !({b})")
  (constraint clearance (min {lv}mm))
  (constraint hole_clearance (min {lv}mm)))

(rule "mains_between_nets"
  (condition "({a}) && ({b}) && A.Net != B.Net")
  (constraint clearance (min {mm}mm)))

# Pad-to-pad spacing inside a component is set by its manufacturer (K1 COM/NO
# pins 5 mm apart, PS1 AC pins 5.08 mm apart): accepted down to {rc} mm, for the
# pads of K1 and of PS1 only.
(rule "mains_pad_to_pad_inside_components"
  (condition "A.Type == 'Pad' && B.Type == 'Pad' && ({a}) && ({b}) && A.Net != B.Net && ((A.insideCourtyard('K1') && B.insideCourtyard('K1')) || (A.insideCourtyard('PS1') && B.insideCourtyard('PS1')))")
  (constraint clearance (min {rc}mm)))

# The plastic locating peg of the F1 holder (NPTH, between its two clips) is not a
# conductor: ordinary hole clearance.
(rule "mains_f1_holder_peg"
  (condition "({a}) && B.Type == 'Pad' && !B.isPlated() && B.insideCourtyard('F1')")
  (constraint hole_clearance (min 1mm)))

(rule "mains_board_edge"
  (condition "{a}")
  (constraint edge_clearance (min 1mm)))
""".format(a=mains, b=mains_b, lv=MAINS_TO_LV, mm=MAINS_TO_MAINS, rc=RELAY_CONTACT_GAP)
    with open(DRU, "w") as f:
        f.write(txt)


if __name__ == "__main__":
    write_project()
    write_rules()
    print("project and rules written")
