"""Export the board geometry used by the enclosure model (enclosure/board.json).

The enclosure (CadQuery, SPEC 4.12) is derived from this file rather than from a STEP
export: several footprints have no 3D model (WAGO, K1, PS1 drill variants) and the
KiCad 7 STEP exporter would silently drop them. Heights come from the datasheets.

  python3 export_board.py            (run after `make pcb`/`make route`)
  python3 export_board.py --check    compare with the committed file, 0.1 mm tolerance
                                     (KiCad versions round bounding boxes differently)
"""
import json
import math
import os
import sys

import pcbnew

import pcb as P

OUT = os.path.normpath(os.path.join(P.HW, "..", "enclosure", "board.json"))

# Height of each part above the PCB top face (mm), worst case, with its source.
HEIGHTS = {
    "K1": (15.7, "Omron G5RL datasheet: 15.7 max"),
    "PS1": (15.0, "Mean Well IRM-03 datasheet: 37*24*15 mm (PCB mounting style)"),
    "C7": (17.5, "Nichicon UHW 10x16: L=16 + tolerance/seat (to confirm on the part)"),
    "F1": (11.5, "KiCad 3D model Schurter 0031.8201 open holder: 11.5"),
    "F2": (21.0, "Littelfuse FLR 178.6165: holder 17.5 + ATO fuse above it (to confirm)"),
    "RV1": (16.0, "10D disc 12.5 max + formed leads (to confirm)"),
    "J1": (16.7, "WAGO 2604 datasheet: 16.7 lever closed, 25.7 open"),
    "J4": (16.7, "WAGO 2604"), "J7": (16.7, "WAGO 2604"), "J5": (16.7, "WAGO 2604"),
    "J6": (16.7, "WAGO 2604"), "J8": (16.7, "WAGO 2604"),
    "U1": (3.3, "ESP32-C3-MINI-1 module + shield"),
    "SW1": (2.5, "C&K PTS810: 2.5 (actuator top)"),
    "J3": (0.1, "pads only, header not fitted"),
    "J2": (2.0, "soldered DMX tail (wires leave upwards)"),
    "H1": (0.0, "hole"), "H2": (3.0, "M3 screw head"), "H3": (3.0, "M3 screw head"),
}
DEFAULT_H = (2.5, "SMD part (SOIC/DPAK/SMB <= 2.4)")
WAGO_LEVER_OPEN = 25.7


def mm(v):
    return pcbnew.ToMM(v)


def main():
    board = pcbnew.LoadBoard(P.PCB)
    parts, pads, holes = [], [], []
    for fp in board.GetFootprints():
        ref = fp.GetReference()
        if ref == "MB":
            continue
        cy = fp.GetCourtyard(pcbnew.F_CrtYd)
        bb = cy.BBox() if cy.OutlineCount() else fp.GetBoundingBox(False, False)
        h, src = HEIGHTS.get(ref, DEFAULT_H)
        parts.append({"ref": ref, "box": [round(mm(bb.GetLeft()) - P.OX, 2), round(mm(bb.GetTop()) - P.OY, 2),
                                          round(mm(bb.GetRight()) - P.OX, 2), round(mm(bb.GetBottom()) - P.OY, 2)],
                      "height": h, "source": src,
                      "strip": mm(bb.GetLeft()) - P.OX > P.SPLIT_X})
        for pad in fp.Pads():
            x, y = mm(pad.GetPosition().x) - P.OX, mm(pad.GetPosition().y) - P.OY
            r = max(mm(pad.GetSize().x), mm(pad.GetSize().y)) / 2
            pads.append([round(x, 2), round(y, 2), round(r, 2)])
            if ref.startswith("H"):
                holes.append({"ref": ref, "x": round(x, 2), "y": round(y, 2),
                              "d": round(mm(pad.GetDrillSize().x), 2)})
    # stable order whatever the KiCad version iterates in
    parts.sort(key=lambda q: q["ref"])
    holes.sort(key=lambda q: q["ref"])
    pads.sort()
    geo = {
        "comment": "Generated by hardware/gen/export_board.py - do not edit",
        "thickness": 1.6,
        # board = union of rectangles (x1, y1, x2, y2); Y grows downwards (KiCad)
        "rects": [[0.0, 0.0, P.W, P.H], [0.0, -P.FUSE_BAND, P.BAND_X, 0.0]],
        "split_x": P.SPLIT_X, "slot_w": P.SLOT_W, "tabs": P.TABS,
        "cut_edge_x": P.BITE_X + P.BITE_D / 2,      # main part edge once the tabs are snapped
        "iso_slot_x": P.SLOT_X, "iso_slot_w": 1.2, "iso_slots": P.SLOTS,
        "mains_max_x": P.MAINS_MAX_X, "lv_min_x": P.LV_MIN_X,
        "antenna": list(P.ANTENNA_KEEPOUT),
        "holes": holes, "parts": parts, "pads": pads,
        "wago_lever_open": WAGO_LEVER_OPEN,
    }
    geo["supports"] = support_points(geo)
    if "--check" in sys.argv:
        return compare(json.load(open(OUT)), json.loads(json.dumps(geo)))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        json.dump(geo, f, indent=1)
    print("written", OUT, "-", len(parts), "parts,", len(geo["supports"]), "support points")


def compare(old, new, tol=0.1):
    """Numeric comparison of two exports; prints and counts the differences."""
    diffs = []

    def walk(a, b, path):
        if isinstance(a, dict) and isinstance(b, dict):
            for k in sorted(set(a) | set(b)):
                if k not in a or k not in b:
                    diffs.append("%s/%s missing on one side" % (path, k))
                else:
                    walk(a[k], b[k], path + "/" + str(k))
        elif isinstance(a, list) and isinstance(b, list):
            if len(a) != len(b):
                diffs.append("%s: %d vs %d items" % (path, len(a), len(b)))
            for i, (x, y) in enumerate(zip(a, b)):
                walk(x, y, "%s[%d]" % (path, i))
        elif isinstance(a, (int, float)) and isinstance(b, (int, float)) and not isinstance(a, bool):
            if abs(a - b) > tol:
                diffs.append("%s: %s vs %s" % (path, a, b))
        elif a != b:
            diffs.append("%s: %r vs %r" % (path, a, b))

    walk(old, new, "")
    for d in diffs[:40]:
        print("  ", d)
    print("board.json: %d difference(s) beyond %.2f mm" % (len(diffs), tol))
    return 1 if diffs else 0


def support_points(geo):
    """Plastic posts under the PCB (and lid pressers above them): >= 3 mm from any pad,
    >= 2.5 mm from every courtyard (room for a 4 mm presser), >= 2.5 mm from edges and
    slots. One set per board zone."""
    def on_board(x, y, m):
        return any(r[0] + m <= x <= r[2] - m and r[1] + m <= y <= r[3] - m for r in geo["rects"])

    def ok(x, y):
        if not on_board(x, y, 2.5):
            return False
        if abs(x - P.SLOT_X) < 2.5 or abs(x - P.SPLIT_X) < P.SPLIT_KEEP + 1:
            return False
        if any(math.hypot(x - px, y - py) < pr + 3.0 for px, py, pr in geo["pads"]):
            return False
        return True

    def free_above(x, y):
        return not any(b["box"][0] - 2.5 <= x <= b["box"][2] + 2.5 and b["box"][1] - 2.5 <= y <= b["box"][3] + 2.5
                       for b in geo["parts"])

    # wanted locations (zone, x, y, presser): the nearest valid grid point is taken.
    # With a presser the lid clamps the PCB there, so the point must also be clear of
    # every part on top; without, it is only a post under the board (THT leads only).
    wants = [("mains", 8.0, -6.0, True), ("mains", 20.0, 46.0, True), ("mains", 20.0, 5.0, True),
             ("main", 97.0, 30.0, False), ("strip", 128.0, 3.0, True), ("strip", 137.0, 40.0, False),
             ("strip", 104.0, 22.0, False)]
    grid = [(x / 2, y / 2) for x in range(0, 293) for y in range(-23, 109)]
    good = [p for p in grid if ok(*p)]
    out = []
    for zone, wx, wy, presser in wants:
        cand = [p for p in good if (zone == "mains") == (p[0] < P.SLOT_X)
                and (zone == "strip") == (p[0] > P.SPLIT_X) and (not presser or free_above(*p))]
        if not cand:
            continue
        x, y = min(cand, key=lambda p: math.hypot(p[0] - wx, p[1] - wy))
        if math.hypot(x - wx, y - wy) < 8:
            out.append({"zone": zone, "x": x, "y": y, "presser": presser})
    return out


if __name__ == "__main__":
    sys.exit(main())
