"""Stored show format (PROTOCOL §10) checked against the vectors shared with the firmware."""
import argparse
import importlib.util
import json
import os
import struct

import pytest

from dmxnow import show

VECTORS = os.path.join(os.path.dirname(__file__), "..", "..", "firmware", "common", "test_vectors.json")
V = json.load(open(VECTORS))["show"]


def vector_show():
    s = show.Show("feu", [show.rel(1), show.rel(2), show.abs_slot(20)], resume_s=5)
    s.step(300, [10, 100, 255]).step(200, [210, 100, 0]).step(0, [50, 50, 50])
    return s


def test_encoding_matches_the_firmware_vector():
    assert vector_show().encode().hex() == V["valid"][0]["hex"]


def test_render_matches_the_firmware_vector():
    v = V["valid"][0]
    s = show.Show.decode(bytes.fromhex(v["hex"]))
    start = v["start_address"]
    for r in v["renders"]:
        want = dict((k, val) for k, val in r["slots"])
        got = s.render(r["t"])
        idx = [start, start + 1, 19]   # rel 1, rel 2 from start_address 6, then abs 20
        assert {i: x for i, x in zip(idx, got)} == want, r["t"]


@pytest.mark.parametrize("vec", V["invalid"], ids=lambda v: v["name"])
def test_invalid_files_refused(vec):
    raw = bytes.fromhex(vec["hex"])
    with pytest.raises(ValueError):
        show.Show.decode(raw)


def test_builder_limits():
    with pytest.raises(ValueError):
        show.rel(512)
    with pytest.raises(ValueError):
        show.abs_slot(0)
    s = show.Show("x", [show.rel(1)])
    with pytest.raises(ValueError):
        s.step(10, [1, 2])
    with pytest.raises(ValueError):
        s.encode()   # no keyframe
    s.step(0, [300])
    assert s.steps[0][1] == [255]   # clamped
    with pytest.raises(ValueError):
        s.encode()   # loop of 0 ms


def test_chunks_cover_the_file_and_fit_a_command():
    data = bytes(range(256)) * 3
    parts = list(show.chunks(data))
    assert b"".join(c for _, c in parts) == data
    assert all(off == i * show.WRITE_CHUNK for i, (off, _) in enumerate(parts))
    # 250-byte command packet: header 18 + target 6 + opcode 1 + offset 4 + data + auth 12
    assert 18 + 6 + 1 + 4 + show.WRITE_CHUNK + 12 <= 250


def test_decode_info():
    raw = struct.pack("<BB16sIIIIHH", 1, 0, b"pixels", 123, 0xDEADBEEF, 3, 500, 5, 300)
    assert show.decode_info(raw) == {"loaded": True, "playing": False, "name": "pixels", "size": 123,
                                     "crc32": "deadbeef", "keyframes": 3, "loop_s": 0.5, "resume_s": 5,
                                     "channels": 300}
    assert show.decode_info(bytes(38)) == {"loaded": False, "playing": False}
    old = struct.pack("<BB16sIIIIHB", 1, 0, b"feu", 123, 0xDEADBEEF, 3, 500, 5, 4)   # node firmware before u16
    assert show.decode_info(old)["channels"] == 4


def test_strip_vector_over_255_channels():
    v = V["valid"][1]
    s = show.Show("pixels", [show.abs_slot(c) for c in range(41, 341)])
    s.step(400, [i % 256 for i in range(300)]).step(600, [255 - i % 256 for i in range(300)])
    assert s.encode().hex() == v["hex"]
    d = show.Show.decode(bytes.fromhex(v["hex"]))
    for r in v["renders"]:
        assert [[40 + i, x] for i, x in enumerate(d.render(r["t"]))] == r["slots"], r["t"]
    with pytest.raises(ValueError):
        show.Show("x", [show.abs_slot(1)] * 513).step(10, [0] * 513).encode()


def test_fireplace_file_matches_its_script():
    """shows/feu-de-cheminee.dxs is regenerated by its script (fixed seed): same bytes,
    and the loop closes without a jump (no step larger than a normal flicker)."""
    root = os.path.join(os.path.dirname(__file__), "..", "..", "shows")
    spec = importlib.util.spec_from_file_location("feu", os.path.join(root, "feu_de_cheminee.py"))
    feu = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(feu)
    args = argparse.Namespace(minutes=5, brightness=100, relay_dmx=1, fixture_rgb=None, fixture_dimmer=None,
                              resume_s=5, seed=2026)
    data = feu.build(args).encode()
    assert data == open(os.path.join(root, "feu-de-cheminee.dxs"), "rb").read()
    s = show.Show.decode(data)
    jumps = [abs(a - b) for (_, x), (_, y) in zip(s.steps, s.steps[1:] + s.steps[:1]) for a, b in zip(x, y)]
    seam = max(abs(a - b) for a, b in zip(s.steps[-1][1], s.steps[0][1]))
    assert seam <= sorted(jumps)[int(len(jumps) * 0.99)]


def test_pixel_strip_files_match_their_script():
    """shows/pixels/*.dxs (20 shows for a 100-pixel WS2811 strip behind a SP201E at 41) are
    regenerated by shows/ruban_pixels.py: same bytes, 300 channels 41 to 340, under 128 ko."""
    root = os.path.join(os.path.dirname(__file__), "..", "..", "shows")
    spec = importlib.util.spec_from_file_location("ruban_pixels", os.path.join(root, "ruban_pixels.py"))
    rp = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(rp)
    args = argparse.Namespace(addr=41, pixels=100, order="RBG", brightness=100, resume_s=5, seed=2026)
    files = sorted(os.listdir(os.path.join(root, "pixels")))
    assert len(files) == len(rp.SHOWS) == 20
    for k, fn in enumerate(rp.SHOWS, 1):
        name = f"{k:02d}-{rp.show_name(fn)}.dxs"
        data = rp.build(fn, args).encode()
        assert data == open(os.path.join(root, "pixels", name), "rb").read(), name
        s = show.Show.decode(data)
        assert s.channels == list(range(41, 341)) and len(data) <= show.MAX_SIZE
